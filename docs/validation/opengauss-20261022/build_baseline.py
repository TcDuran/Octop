"""Build a reviewable static baseline from a freshly migrated PostgreSQL DB.

Usage: uv run python docs/validation/opengauss-20261022/build_baseline.py
The source dump is generated with pg_dump 16 --schema-only --no-owner
--no-privileges after run_migrations() at fork commit cc623be1. This is a
build-time conversion of that known schema, never a runtime SQL translator.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
source = (ROOT / "data/opengauss/baseline.pg.sql").read_text()
lines = [line for line in source.splitlines() if not line.startswith(("--", "\\"))]
text = "\n".join(lines)
statements = [part.strip() for part in text.split(";") if part.strip()]
output = [
    "-- openGauss 6.0.5, PG compatibility, Astore. Fresh install only.",
    "-- Baseline: control-plane v22, fork cc623be1 (including post-migration ensures).",
    "-- Generated by docs/validation/opengauss-20261022/build_baseline.py.",
    "-- Execute in a transaction in an empty public schema. Do not replay on existing tables.",
    "-- Identity widths are preserved with bounded, owned sequences.",
]
for statement in statements:
    if statement.startswith(("SET ", "SELECT pg_catalog.set_config")):
        continue
    identity = re.fullmatch(
        r"ALTER TABLE public\.(\w+) ALTER COLUMN (\w+) ADD GENERATED BY DEFAULT AS IDENTITY "
        r"\(\s*SEQUENCE NAME public\.(\w+).*\)",
        statement,
        re.S,
    )
    if identity:
        table, column, sequence = identity.groups()
        table_ddl = re.search(rf"CREATE TABLE public\.{table} \((.*?)\n\)", source, re.S)
        assert table_ddl
        kind = re.search(rf"\b{column} (integer|bigint) NOT NULL", table_ddl[1])
        assert kind, (table, column)
        maximum = 2147483647 if kind[1] == "integer" else 9223372036854775807
        output.extend(
            [
                f"CREATE SEQUENCE public.{sequence} START WITH 1 INCREMENT BY 1 "
                f"MINVALUE 1 MAXVALUE {maximum} CACHE 1;",
                f"ALTER SEQUENCE public.{sequence} OWNED BY public.{table}.{column};",
                f"ALTER TABLE public.{table} ALTER COLUMN {column} "
                f"SET DEFAULT nextval('public.{sequence}'::regclass);",
            ]
        )
        continue
    if statement.startswith("CREATE TABLE "):
        statement += " WITH (storage_type=ASTORE)"
    output.append(statement + ";")

# Seeds are the values produced by the canonical fresh PostgreSQL migrations.
# Permissions are deliberately static for this version; future changes need a migration.
output.extend(
    [
        "INSERT INTO public.settings(key, value) VALUES "
        "('active_stt_provider', 'browser'), ('active_tts_provider', 'browser'), "
        "('granted_nav_page_permissions', '1'), ('granted_personalization_tab_permissions', '1');",
        "INSERT INTO public.user_role(user_role_id, user_role_name, permissions, policies, "
        "created_at, updated_at) VALUES "
        "('admin', '管理员', '[]', '[]', "
        "CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) AS INTEGER), "
        "CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) AS INTEGER)), "
        "('user', '用户', "
        '\'["agent_plugins", "channels", "connectors", "experts", "knowledge_bases", '
        '"mbti", "memory", "skill_packages", "skills", "subagents", "tasks", '
        '"token_usage", "tools"]\', \'[]\', '
        "CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) AS INTEGER), "
        "CAST(EXTRACT(EPOCH FROM CURRENT_TIMESTAMP) AS INTEGER));",
        "INSERT INTO public._schema_version(version) VALUES (22);",
        "COMMENT ON TABLE public._schema_version IS 'octop:opengauss:baseline22';",
    ]
)
(ROOT / "src/octop/infra/db/opengauss/022_baseline.sql").write_text("\n\n".join(output) + "\n")
print(f"baseline: {len(output)} blocks, {len(re.findall('CREATE TABLE ', source))} tables")
